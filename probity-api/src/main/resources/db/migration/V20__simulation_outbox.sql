-- Transactional outbox for simulation requested events (Phase 4 §5 M1).
--
-- Guarantees that an accepted simulation cannot silently disappear before
-- reaching the worker. The simulation row and the outbox event are committed
-- in the same PostgreSQL transaction. A separate publisher in the worker reads
-- pending outbox records and publishes them to Kafka, marking each as published
-- only after successful Kafka acknowledgement.
--
-- Delivery is at-least-once and nothing is ever dropped by the publisher:
--   * a publisher leases rows with claim_token + claimed_until, commits that
--     lease, and only then performs the blocking Kafka send. No row lock is
--     held while waiting for the broker;
--   * the success/failure write is fenced on claim_token, so a publisher whose
--     lease lapsed cannot overwrite a newer claim;
--   * a failed row keeps error_count (for alerting) and claimed_until is pushed
--     forward as exponential backoff, so the row stays queued and is retried
--     forever. There is no attempt limit that marks a row dead.
--
-- Conventions (matching V18/V19):
--   - Conditional role grants are idempotent and no-op if the role is absent.
--   - UUIDs are generated by the application, not by Hibernate (to keep the
--     outbox id independent of the simulation id, though they are often the same).
--   - TIMESTAMPTZ for all Java Instant columns.
-- =============================================================================

CREATE TABLE IF NOT EXISTS simulation_outbox (
    id UUID NOT NULL,
    simulation_id UUID NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ,
    error_count INTEGER NOT NULL DEFAULT 0,
    claim_token UUID,
    claimed_until TIMESTAMPTZ,

    CONSTRAINT pk_simulation_outbox PRIMARY KEY (id),
    CONSTRAINT uq_simulation_id UNIQUE (simulation_id)
);

-- The publisher only ever scans unpublished rows, in creation order; a partial
-- index keeps the claim query cheap as published history accumulates.
CREATE INDEX IF NOT EXISTS idx_simulation_outbox_pending
    ON simulation_outbox (created_at)
    WHERE published_at IS NULL;

COMMENT ON TABLE simulation_outbox
    IS 'Transactional outbox for simulation requested events. One row per accepted simulation. '
    'The simulation row and this event are written in the same transaction.';

COMMENT ON COLUMN simulation_outbox.id
    IS 'Primary key; generated UUID (often same as simulation_id)';

COMMENT ON COLUMN simulation_outbox.simulation_id
    IS 'Links to the simulations row. UNIQUE ensures one event per simulation.';

COMMENT ON COLUMN simulation_outbox.event_type
    IS 'Type identifier; currently always SimulationRequestedEvent.';

COMMENT ON COLUMN simulation_outbox.payload
    IS 'JSONB serialisation of SimulationRequestedEvent.';

COMMENT ON COLUMN simulation_outbox.created_at
    IS 'When the outbox row was inserted (same as simulations.created_at)';

COMMENT ON COLUMN simulation_outbox.published_at
    IS 'When the event was successfully published to Kafka. Null if not yet published.';

COMMENT ON COLUMN simulation_outbox.error_count
    IS 'Consecutive publication failure count. Used for alerting and exponential backoff; '
    'a row is never dropped when it reaches a threshold.';

COMMENT ON COLUMN simulation_outbox.claim_token
    IS 'Fencing token of the publisher that currently owns this row. Cleared on publish; '
    'a stale publisher whose lease lapsed cannot overwrite a newer claim.';

COMMENT ON COLUMN simulation_outbox.claimed_until
    IS 'Lease expiry. The row is claimable again once this passes; on failure it is pushed '
    'forward as exponential backoff, so a failed row stays queued.';

-- =============================================================================
-- Grants — guarded and idempotent in the style of V18/V19
-- =============================================================================
-- probity_worker runs the publisher: it SELECTs pending rows, leases them with
-- UPDATE, and writes published_at / error_count with UPDATE. It does not INSERT
-- or DELETE outbox rows.
--
-- The api writes the outbox row inside the run-async transaction. In today's
-- deployment it connects as the migration owner (same as every other api write),
-- so no grant is required. A dedicated probity_api role, if one is introduced,
-- gets exactly SELECT + INSERT.
DO $$
BEGIN
    IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'probity_worker') THEN
        GRANT SELECT, UPDATE ON simulation_outbox TO probity_worker;
    END IF;

    IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'probity_api') THEN
        GRANT SELECT, INSERT ON simulation_outbox TO probity_api;
    END IF;
END $$;
